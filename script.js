// 🔍 BUSCADOR SOLO NÚMEROS
function buscarMundial(){
  let query = document.getElementById("buscador").value;
  query = query.replace(/\D/g, "");
  document.getElementById("buscador").value = query;
  
  if(query === "") {
    alert("Por favor ingresa un año válido.");
    return;
  }

  let encontrado = false;
  mundiales.forEach(m => {
    if(m.anio.toString() === query){
      document.getElementById("y"+m.anio)?.scrollIntoView({behavior:"smooth"});
      encontrado = true;
    }
  });
  
  if(!encontrado){
    alert("No se encontró ningún Mundial con ese año.");
  }
}

// 📋 AUTOCOMPLETAR SOLO POR AÑOS
function mostrarSugerencias(){
  const query = document.getElementById("buscador").value;
  const sugerenciasDiv = document.getElementById("sugerencias");
  sugerenciasDiv.innerHTML = "";
  
  if(query.length < 2) return;

  const resultados = mundiales.filter(m =>
    m.anio.toString().startsWith(query)
  );
  
  resultados.forEach(m => {
    const sug = document.createElement("div");
    sug.textContent = m.anio;
    sug.onclick = () => {
      document.getElementById("buscador").value = m.anio;
      buscarMundial();
      sugerenciasDiv.innerHTML = "";
    };
    sugerenciasDiv.appendChild(sug);
  });
}

// 🎯 FILTROS EXACTOS
function filtrarMundiales(){
  const campeon = document.getElementById("filtroCampeon").value.toLowerCase();
  const sede = document.getElementById("filtroSede").value.toLowerCase();
  
  document.querySelectorAll(".mundial").forEach(sec => {
    const sedeTexto = sec.querySelector("p b")?.nextSibling?.textContent?.toLowerCase() || "";
    const campeonTexto = Array.from(sec.querySelectorAll("p"))
                              .map(p => p.textContent.toLowerCase())
                              .find(t => t.includes("🥇")) || "";

    const coincideCampeon = campeon === "" || campeonTexto.includes(campeon);
    const coincideSede = sede === "" || sedeTexto.trim() === sede;

    if(coincideCampeon && coincideSede){
      sec.style.display = "block";
    } else {
      sec.style.display = "none";
    }
  });
}

// 🔄 RESET FILTROS
function resetFiltros(){
  document.getElementById("filtroCampeon").value = "";
  document.getElementById("filtroSede").value = "";
  
  document.querySelectorAll(".mundial").forEach(sec => {
    sec.style.display = "block";
  });
}

